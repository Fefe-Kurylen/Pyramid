const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('native', {
  save: (name, data) => ipcRenderer.invoke('save', { name, data }),
  onOpenFile: cb => ipcRenderer.on('open-file', (e, f) => cb(f)),
  setTitleBar: o => ipcRenderer.send('titlebar', o),
  ready: () => ipcRenderer.send('ready'),
  html2pdf: html => ipcRenderer.invoke('html2pdf', html),
  print: (pages, opts) => ipcRenderer.invoke('print', pages, opts),
  printers: () => ipcRenderer.invoke('printers'),
  tsa: (url, body) => ipcRenderer.invoke('tsa', url, body),
  version: () => ipcRenderer.invoke('app-version'),
  onUpdate: cb => ipcRenderer.on('update', (e, o) => cb(o)),
  ocr: bytes => ipcRenderer.invoke('ocr', bytes),
  scanStart: () => ipcRenderer.invoke('scan-start'),
  scanStop: () => ipcRenderer.invoke('scan-stop'),
  onScan: cb => { ipcRenderer.on('scan-event', (e, o) => cb(o)); ipcRenderer.on('scan-pages', (e, o) => cb({ type: 'pages', pages: o.pages })); },
  scanners: () => ipcRenderer.invoke('scanners'),
  scannerInfo: id => ipcRenderer.invoke('scanner-info', id),
  scannerAdd: addr => ipcRenderer.invoke('scanner-add', addr),
  scannerForget: addr => ipcRenderer.invoke('scanner-forget', addr),
  scannerScan: (id, opts) => ipcRenderer.invoke('scanner-scan', id, opts),
  scannerCancel: () => ipcRenderer.invoke('scanner-cancel'),
  onScanner: cb => ipcRenderer.on('scanner-event', (e, o) => cb(o)),
  updateState: () => ipcRenderer.invoke('update-state'),
  checkUpdate: () => ipcRenderer.invoke('update-check'),
  installUpdate: () => ipcRenderer.invoke('update-install'),
  platform: process.platform
});
